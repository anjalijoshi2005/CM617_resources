import numpy as np
import pandas as pd

# ==========================================
# STEP 1: LOAD DATASET 3 (EPA Vehicles Data)
# ==========================================
# Downloaded from FuelEconomy.gov (vehicles.csv)
df_epa = pd.read_csv("vehicles.csv", low_memory=False)

# Relevant EPA columns:
# - 'comb08': Combined MPG for ICE / conventional vehicles
# - 'combE': Combined electricity consumption in kWh/100 miles for EVs
# - 'fuelType': Gasoline/Electricity
# - 'VClass': Vehicle Class (Sedan, SUV, etc.)

# Convert EPA kWh/100 miles to kWh/km
# (1 mile = 1.60934 km)
df_epa["ev_kwh_per_km"] = (df_epa["combE"] / 100.0) / 1.60934

# Convert EPA MPG to Liters / 100 km
# (1 MPG = 235.215 / MPG in L/100km)
df_epa["ice_l_per_100km"] = 235.215 / df_epa["comb08"]

# Extract average operational efficiency by vehicle class from real data
epa_ev_summary = (
    df_epa[df_epa["fuelType"] == "Electricity"]
    .groupby("VClass")["ev_kwh_per_km"]
    .mean()
)
epa_ice_summary = (
    df_epa[df_epa["fuelType"].str.contains("Gasoline", na=False)]
    .groupby("VClass")["ice_l_per_100km"]
    .mean()
)

print("--- Data Extracted from Dataset 3 (EPA vehicles.csv) ---")
print("Sample EV Efficiency (kWh/km):")
print(epa_ev_summary.head())


# ==========================================
# STEP 2: LOAD DATASET 4 (LCA Parameters)
# ==========================================
df_lca = pd.read_csv("lca_parameters.csv")


# ==========================================
# STEP 3: DYNAMIC LCA & BREAK-EVEN CALCULATION
# ==========================================
# Physical Constants
PETROL_EMISSION_FACTOR = 2.31  # kg CO2e per liter of petrol

# Grid Carbon Intensities from OWID Dataset 1 (kg CO2e / kWh)
grid_intensities = {
    "Norway": 0.025,
    "France": 0.055,
    "United States": 0.370,
    "India": 0.710,
}

# Example vehicle battery capacity mapping (kWh)
battery_capacities = {"Two-Wheeler": 3.5, "Sedan": 50.0, "SUV": 80.0}

results = []

# Dynamically iterate over LCA dataset entries
for _, row in df_lca.iterrows():
  v_category = row["vehicle_category"]
  battery_kwh = battery_capacities.get(v_category, 50.0)

  # Calculate total manufacturing emissions dynamically from LCA parameters
  ice_mfg = row["ice_mfg_co2_kg"]
  ev_mfg = (
      row["ev_body_mfg_co2_kg"]
      + battery_kwh * row["battery_mfg_co2_kg_per_kwh"]
  )

  # Extract operational efficiencies derived from EPA dataset
  # (Using mapped class defaults if specific EPA class string differs)
  if v_category == "Two-Wheeler":
    ice_l_100km = 2.2
    ev_kwh_km = 0.04
  elif v_category == "Sedan":
    ice_l_100km = (
        epa_ice_summary.get("Midsize Cars", 6.8)
        if not np.isnan(epa_ice_summary.get("Midsize Cars", np.nan))
        else 6.8
    )
    ev_kwh_km = (
        epa_ev_summary.get("Midsize Cars", 0.16)
        if not np.isnan(epa_ev_summary.get("Midsize Cars", np.nan))
        else 0.16
    )
  else:  # SUV
    ice_l_100km = (
        epa_ice_summary.get("Standard Sport Utility Vehicle 4WD", 9.5)
        if not np.isnan(
            epa_ice_summary.get("Standard Sport Utility Vehicle 4WD", np.nan)
        )
        else 9.5
    )
    ev_kwh_km = (
        epa_ev_summary.get("Standard Sport Utility Vehicle 4WD", 0.22)
        if not np.isnan(
            epa_ev_summary.get("Standard Sport Utility Vehicle 4WD", np.nan)
        )
        else 0.22
    )

  # Tailpipe ICE operational emissions per km
  ice_op_per_km = (ice_l_100km / 100.0) * PETROL_EMISSION_FACTOR

  for country, grid_kg in grid_intensities.items():
    # EV operational emissions per km
    ev_op_per_km = ev_kwh_km * grid_kg
    op_savings_per_km = ice_op_per_km - ev_op_per_km

    if op_savings_per_km > 0:
      breakeven_km = (ev_mfg - ice_mfg) / op_savings_per_km
      breakeven_years = breakeven_km / row["annual_mileage_km"]
    else:
      breakeven_km = np.inf
      breakeven_years = np.inf

    # 15-Year Lifetime Emissions
    lifetime_km = 15 * row["annual_mileage_km"]
    ice_lifetime_co2 = ice_mfg + (ice_op_per_km * lifetime_km)
    ev_lifetime_co2 = ev_mfg + (ev_op_per_km * lifetime_km)
    co2_savings_pct = (
        (ice_lifetime_co2 - ev_lifetime_co2) / ice_lifetime_co2
    ) * 100

    results.append({
        "Category": v_category,
        "Country": country,
        "ICE Mfg CO2 (kg)": round(ice_mfg, 1),
        "EV Mfg CO2 (kg)": round(ev_mfg, 1),
        "Break-Even (km)": (
            round(breakeven_km, 0)
            if breakeven_km != np.inf
            else "Never (Dirty Grid)"
        ),
        "Break-Even (Years)": (
            round(breakeven_years, 1)
            if breakeven_years != np.inf
            else "Never"
        ),
        "Net Savings (%)": round(co2_savings_pct, 1),
    })

df_final = pd.DataFrame(results)
print("\n--- FINAL DYNAMIC BREAK-EVEN RESULTS ---")
print(df_final.to_string())

